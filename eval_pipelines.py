_NAIVE_RAG_PROMPT = """\
You are an experienced commercial-insurance underwriter. Decide whether to
ACCEPT, REJECT, or REFER_TO_HUMAN_REVIEW.

Use the retrieved guideline excerpts below as context. ACCEPT if the business's
core operations are within appetite and no excerpt is clearly violated — do NOT
withhold acceptance merely because the application doesn't restate or document
every requirement in the excerpts (real applications never do). REJECT if an
excerpt is clearly violated. REFER_TO_HUMAN_REVIEW ONLY when a SPECIFIC, DECISIVE
fact needed to apply a business-specific exclusion is genuinely absent — not for
ordinary undocumented requirements or general ambiguity.

Respond with ONLY a single-line JSON object:
{{"decision": "<ACCEPT|REJECT|REFER_TO_HUMAN_REVIEW>", "reason": "<one short sentence quoting or referencing the relevant excerpt or missing field>"}}

==== APPLICATION ====
{app_text}

==== THIRD-PARTY DATA ====
{tpd_text}

==== RETRIEVED GUIDELINE EXCERPTS ====
{retrieved}
"""


class NaiveRAGPipeline:
    """Retrieve top-K passages from the guidebook PDF, then one LLM call."""

    name = "naive_rag"

    def __init__(self, llm, retriever, threshold: float = 1.75, k: int = 6):
        self.llm = llm
        self.retriever = retriever
        self.threshold = threshold
        self.k = k

    def _retrieve(self, application: dict, third_party: dict) -> str:
        bt = application.get("NATURE OF BUSINESS") or ""
        desc = application.get("DESCRIPTION OF OPERATIONS") or ""
        query = f"Underwriting guidelines and restrictions for {bt}. Operations: {desc[:300]}"
        docs = self.retriever.invoke(query)
        # Deduplicate and limit
        seen = set(); kept = []
        for d in docs[: self.k * 2]:
            if d.page_content in seen:
                continue
            seen.add(d.page_content)
            kept.append(d)
            if len(kept) >= self.k:
                break
        return "\n\n---\n\n".join(d.page_content for d in kept)

    def run(self, application: dict, third_party: dict) -> dict:
        retrieved = self._retrieve(application, third_party)
        prompt = _NAIVE_RAG_PROMPT.format(
            app_text=_app_text(application),
            tpd_text=_tpd_text(third_party),
            retrieved=retrieved or "(no relevant guidelines retrieved)",
        )
        raw = self.llm.invoke(prompt).content.strip()
        data = _parse_decision_json(raw)
        appetite_decision = _normalize_decision(data.get("decision", raw))
        reason = (data.get("reason") or "").strip() or raw[:200]

        if appetite_decision != "ACCEPT":
            return {"decision": appetite_decision, "reason": reason,
                    "appetite_decision": appetite_decision, "logistic_cap": None,
                    "n_retrieved": retrieved.count("---") + 1 if retrieved else 0}

        logit_dec, cap = logistic_decision(application, third_party, self.threshold)
        if logit_dec == "REJECT":
            return {"decision": "REJECT",
                    "reason": f"In appetite but failed statistical risk screen (cap={cap}).",
                    "appetite_decision": appetite_decision, "logistic_cap": cap}
        return {"decision": "ACCEPT", "reason": reason,
                "appetite_decision": appetite_decision, "logistic_cap": cap}



# -----------------------------------------------------------------------------
# Pipeline 3: Agentic RAG  (rewritten — paper-faithful Figure 3)
# -----------------------------------------------------------------------------
# State is split into three independent slots so routing is unambiguous:
#   appetite      ∈ {IN_APPETITE, OUT_OF_APPETITE, UNCLEAR}
#   completeness  ∈ {COMPLETE, MISSING_RECOVERABLE, MISSING_IRRECOVERABLE}
#   tpd_finding   ∈ {REVEALS_VIOLATION, CONFIRMS_CLEAN, STILL_AMBIGUOUS}
# Only the terminal nodes set `final_decision` ∈ {ACCEPT, REJECT, REFER_TO_HUMAN_REVIEW}.
#
# Flow (mirrors Figure 3 in the paper):
#
#   APPETITE_CHECK ─── OUT_OF_APPETITE ──────────────────────────► FINAL_REJECT
#         │
#         ├── IN_APPETITE ─► COMPLETENESS_CHECK
#         │                        ├── COMPLETE ─► LOGISTIC_EVAL ─► ACCEPT / FINAL_REJECT
#         │                        ├── MISSING_RECOVERABLE ─► THIRD_PARTY_EVAL
#         │                        │                                ├── REVEALS_VIOLATION ─► FINAL_REJECT
#         │                        │                                ├── CONFIRMS_CLEAN ─► LOGISTIC_EVAL
#         │                        │                                └── STILL_AMBIGUOUS ─► HUMAN_REVIEW
#         │                        └── MISSING_IRRECOVERABLE ─► HUMAN_REVIEW
#         │
#         └── UNCLEAR ─► REFLECTION (max N) ─► back to APPETITE_CHECK
#                              └── (after N) ─► HUMAN_REVIEW
#
# The reflection node strengthens the retrieval query rather than re-querying
# the same prompt — that's the Agent-3 reflection from the paper.

from typing import TypedDict


class _AgenticState(TypedDict, total=False):
    application: dict
    third_party_data: dict
    # intermediate (none of these are decisions; routing reads them)
    appetite: str
    completeness: str
    tpd_finding: str
    reflection_count: int
    retrieval_query: str
    guidelines: str
    # terminal
    final_decision: str
    reason: str


class AgenticRAGPipeline:
    """Paper-faithful agentic pipeline with proper REFER_TO_HUMAN_REVIEW routing."""

    name = "agentic_rag"

    def __init__(self, llm, retriever, threshold: float = 1.75,
                 max_reflections: int = 2,
                 mandatory_decision_reflection: bool = True,
                 enable_appetite_reflection: bool = True):
        self.llm = llm
        self.retriever = retriever
        self.threshold = threshold
        self.max_reflections = max_reflections
        # Reflection agents:
        #  - mandatory_decision_reflection: a critic that ALWAYS runs on the
        #    tentative decision before it's finalized (paper's critic-executor
        #    pattern). This is the "at least one reflection agent automatically".
        #  - enable_appetite_reflection: the OPTIONAL Agent-3 loop that re-queries
        #    the guidebook when appetite is UNCLEAR (up to max_reflections times).
        self.mandatory_decision_reflection = mandatory_decision_reflection
        self.enable_appetite_reflection = enable_appetite_reflection
        self._graph = self._build_graph()

    # ---- retrieval ----
    def _retrieve(self, business_type: str, application: dict,
                  smart_query: Optional[str] = None) -> str:
        business_docs = self.retriever.invoke(
            f"Underwriting guidelines and appetite rules for {business_type}")
        global_docs = self.retriever.invoke(
            "General underwriting guidelines, exclusions, and prohibited operations")
        extra_docs = []
        if smart_query:
            extra_docs = self.retriever.invoke(smart_query)
        seen = set(); kept = []
        for d in business_docs + global_docs + extra_docs:
            if d.page_content in seen: continue
            seen.add(d.page_content); kept.append(d)
        return "\n\n---\n\n".join(d.page_content for d in kept[:12])

    # ---- Agent 1: appetite check ----
    def _node_appetite_check(self, state):
        app = state["application"]
        bt = app.get("NATURE OF BUSINESS") or app.get("BUSINESS TYPE") or "Unknown"
        guidelines = self._retrieve(bt, app, smart_query=state.get("retrieval_query"))
        state["guidelines"] = guidelines

        prompt = (
            f"You are an experienced commercial-insurance underwriter (Agent 1) "
            f"evaluating a Business Owner Policy application for the business "
            f"type: {bt}.\n\n"
            f"=== APPLICATION ===\n{_app_text(app)[:9000]}\n\n"
            f"=== UNDERWRITING GUIDELINES ===\n{guidelines[:6000]}\n\n"
            "Classify the application into EXACTLY ONE of three categories:\n"
            "  IN_APPETITE       — The business's core operations fall within "
            "appetite and nothing in the application evidences a violation of a "
            "business-specific exclusion. This is the DEFAULT for a normal, "
            "compliant-looking application.\n"
            "  OUT_OF_APPETITE   — The application evidences that the business "
            "violates at least one specific guideline (the prohibited activity is "
            "described or clearly implied).\n"
            "  UNCLEAR           — Reserve this ONLY for when a SPECIFIC, DECISIVE "
            "business-specific exclusion cannot be determined because the relevant "
            "fact is genuinely absent (e.g. for a photography studio you cannot "
            "tell whether they use drones; for a restaurant you cannot tell the "
            "alcohol share).\n\n"
            "IMPORTANT — do NOT return UNCLEAR for incidental gaps. A real "
            "application never restates every guideline. The following are NOT "
            "reasons for UNCLEAR: missing documentation/dates, unstated routine "
            "safety programs, ancillary coverages (liquor/auto) that don't by "
            "themselves prove a prohibited operation, generic questionnaire items, "
            "or anything not tied to a SPECIFIC business-specific exclusion. When "
            "the core business is clearly in appetite and no decisive exclusion is "
            "in question, return IN_APPETITE.\n\n"
            "Respond on a single line as JSON: "
            '{"appetite": "<IN_APPETITE|OUT_OF_APPETITE|UNCLEAR>", '
            '"reason": "<one sentence citing the specific guideline / missing fact>"}'
        )
        data = _parse_decision_json(self.llm.invoke(prompt).content)
        a = (data.get("appetite") or "").strip().upper()
        if a not in ("IN_APPETITE", "OUT_OF_APPETITE", "UNCLEAR"):
            a = "UNCLEAR"
        state["appetite"] = a
        state["reason"] = (data.get("reason") or "")[:400]
        return state

    # ---- Agent 3: reflection (refine retrieval query, then loop) ----
    def _node_reflection(self, state):
        state["reflection_count"] = state.get("reflection_count", 0) + 1
        app = state["application"]
        bt = app.get("NATURE OF BUSINESS") or "Unknown"
        prompt = (
            f"You are a reflective underwriting agent (Agent 3). The previous "
            f"appetite check on this {bt} application returned UNCLEAR with "
            f"reason: '{state.get('reason','')}'.\n\n"
            "Write ONE concise retrieval query (single line, <40 words) that would "
            "surface the specific underwriting rule(s) needed to resolve this "
            "ambiguity. Focus on edge-case exclusions or business-specific rules "
            "that might apply.\n\n"
            "Respond with ONLY the query text, no preamble."
        )
        try:
            q = self.llm.invoke(prompt).content.strip().splitlines()[0][:300]
        except Exception:
            q = ""
        state["retrieval_query"] = q
        return state

    # ---- Completeness check (catches incomplete_* scenarios) ----
    def _node_completeness_check(self, state):
        app = state["application"]
        bt = app.get("NATURE OF BUSINESS") or "Unknown"
        guidelines = state.get("guidelines") or self._retrieve(bt, app)
        # Presence-detection (not a sufficiency judgment): a weak model handles
        # "does an affirmative compliance disclaimer EXIST?" far better than
        # "is coverage complete?". Compliant applicants include explicit "we do
        # not do X" disclaimers / a compliance-confirmation statement; incomplete
        # applicants describe the business and stay silent on prohibited activities.
        prompt = (
            f"Read the {bt} application below and answer ONE factual question.\n\n"
            "QUESTION: In its free-text operations narrative (e.g. DESCRIPTION OF "
            "OPERATIONS or a 'Compliance Confirmation' statement), does the "
            "applicant proactively disclaim engaging in activities that are "
            "specifically RESTRICTED for THIS kind of business — e.g. a "
            "photography studio stating it does not use drones, a contractor "
            "stating it does no structural/load-bearing work, an accounting firm "
            "stating it does not provide investment advice?\n\n"
            "CRITICAL — what does NOT count:\n"
            "  - The standard general-information questionnaire (items labeled "
            "G1-G16, e.g. hazardous materials, athletic teams, manufacturing, "
            "workers' comp). EVERY application answers those; ignore them entirely.\n"
            "  - Generic boilerplate ('we comply with all laws/regulations').\n"
            "  - Descriptions of what the business DOES.\n\n"
            "Answer YES only if the operations narrative volunteers a disclaimer "
            "of a BUSINESS-TYPE-SPECIFIC restricted activity (naming the activity). "
            "Answer NO if the narrative just describes the business and the only "
            "'no' answers are in the standard G1-G16 questionnaire.\n\n"
            f"=== APPLICATION ===\n{_app_text(app)[:9000]}\n\n"
            "Respond on a single line as JSON: "
            '{"has_compliance_disclaimer": <true|false>, '
            '"quote": "<a short quote of the disclaimer if present, else empty>"}'
        )
        data = _parse_decision_json(self.llm.invoke(prompt).content)
        has_disclaimer = bool(data.get("has_compliance_disclaimer", False))
        # Map to the completeness vocabulary the router understands.
        return_complete = has_disclaimer
        data = _parse_decision_json(self.llm.invoke(prompt).content)
        # has_compliance_disclaimer present -> COMPLETE (finalize via logistic);
        # absent -> the app is silent, route through the third-party check, which
        # decides REJECT (TPD reveals the violation -> incomplete_recoverable) vs
        # REFER (TPD also silent -> incomplete_irrecoverable).
        if return_complete:
            state["completeness"] = "COMPLETE"
        else:
            state["completeness"] = "MISSING_RECOVERABLE"
            state["reason"] = ("Application contains no affirmative compliance "
                               "disclaimer for its business-specific exclusions.")
        return state

    # ---- Third-party check ----
    def _node_third_party_eval(self, state):
        app = state["application"]; tpd = state["third_party_data"]
        bt = app.get("NATURE OF BUSINESS") or "Unknown"
        guidelines = state.get("guidelines") or self._retrieve(bt, app)
        looking_for = state.get("reason") or "(any underwriting-relevant detail)"
        prompt = (
            "You are Agent 2 again — now searching the third-party data for the "
            "missing information you flagged.\n\n"
            f"Business type: {bt}\n"
            f"Missing information you need: {looking_for}\n\n"
            f"=== THIRD-PARTY DATA ===\n{_tpd_text(tpd)}\n\n"
            f"=== UNDERWRITING GUIDELINES ===\n{guidelines[:5000]}\n\n"
            "Classify the third-party finding as EXACTLY ONE of:\n"
            "  REVEALS_VIOLATION  — Third-party data explicitly shows the business "
            "engaging in the prohibited / restricted activity (e.g. a review "
            "mentions the excluded service).\n"
            "  CONFIRMS_CLEAN     — Third-party data SPECIFICALLY addresses the "
            "missing exclusion and affirmatively establishes the business does NOT "
            "engage in it. Generic praise or unrelated positive reviews do NOT "
            "count — the data must speak to the specific missing fact.\n"
            "  STILL_AMBIGUOUS    — Third-party data does not speak to the missing "
            "exclusion at all (only generic reviews / ratings / claims unrelated to "
            "it). This is the correct answer whenever the data is silent on the "
            "specific fact you need — do NOT infer compliance from general "
            "positivity.\n\n"
            "Respond on a single line as JSON: "
            '{"tpd_finding": "<REVEALS_VIOLATION|CONFIRMS_CLEAN|STILL_AMBIGUOUS>", '
            '"reason": "<one sentence citing the specific evidence>"}'
        )
        data = _parse_decision_json(self.llm.invoke(prompt).content)
        f = (data.get("tpd_finding") or "").strip().upper()
        if f not in ("REVEALS_VIOLATION", "CONFIRMS_CLEAN", "STILL_AMBIGUOUS"):
            f = "STILL_AMBIGUOUS"
        state["tpd_finding"] = f
        state["reason"] = (data.get("reason") or state.get("reason", ""))[:400]
        return state

    # ---- Logistic gate (runs first for in-appetite cases) ----
    # A quantitative hard-fail (cap above threshold) short-circuits to REJECT.
    # This is what separates reject_logit (compliant but high risk) from the
    # incomplete scenarios, which pass the risk screen but are silent on a
    # material exclusion. Only apps that PASS the screen continue to the
    # completeness/third-party checks.
    def _node_logistic_gate(self, state):
        app = state["application"]; tp = state["third_party_data"]
        try:
            dec, cap = logistic_decision(app, tp, self.threshold)
            state["logistic_cap"] = cap
            state["logistic_pass"] = (dec == "ACCEPT")
            if dec == "REJECT":
                state["reason"] = (state.get("reason") or "") + \
                    f" Failed statistical risk screen (cap={cap})."
        except Exception:
            state["logistic_cap"] = None
            state["logistic_pass"] = False
        return state

    # ---- Tentative-decision nodes (set tentative_*, NOT final) ----
    def _node_accept(self, state):
        state["tentative_decision"] = "ACCEPT"
        cap = state.get("logistic_cap")
        base = state.get("reason") or "Application is compliant."
        state["reason"] = (f"{base} Passed risk screen (cap={cap})."
                           if cap is not None else base)
        return state

    def _node_final_reject(self, state):
        state["tentative_decision"] = "REJECT"
        if not state.get("reason"):
            state["reason"] = "Rejected by underwriting guidelines."
        return state

    def _node_human(self, state):
        state["tentative_decision"] = "REFER_TO_HUMAN_REVIEW"
        if not state.get("reason"):
            state["reason"] = "Insufficient information to render an automated decision."
        return state

    # ---- Mandatory critic (always runs): false-accept catcher ----
    # The critic's job is narrow and safe: review a tentative ACCEPT and decide
    # whether the application actually establishes compliance, or whether a
    # material business-specific exclusion is left unaddressed (→ REFER).
    #
    # It deliberately does NOT overturn a REJECT: guideline rejections are
    # evidence-grounded and logistic rejections are a hard quantitative screen —
    # second-guessing either on qualitative grounds caused reject_logit to
    # collapse. REFER tentatives also pass through unchanged.
    def _node_decision_reflection(self, state):
        tentative = state.get("tentative_decision") or "REFER_TO_HUMAN_REVIEW"
        if not self.mandatory_decision_reflection or tentative != "ACCEPT":
            state["final_decision"] = tentative
            return state
        app = state["application"]
        bt = app.get("NATURE OF BUSINESS") or "Unknown"
        guidelines = state.get("guidelines", "")
        prompt = (
            "You are a senior underwriting reviewer performing a final "
            "confirmatory check. This application has ALREADY passed three "
            "independent checks: (1) appetite — its operations are in appetite; "
            "(2) the statistical risk screen; (3) a completeness check that "
            "verified the application affirmatively addresses its business-"
            "specific exclusions. The standing decision is ACCEPT.\n\n"
            "Your DEFAULT is to UPHOLD the ACCEPT. Overturn it to "
            "REFER_TO_HUMAN_REVIEW ONLY if you can point to a SPECIFIC, DECISIVE "
            "business-specific exclusion for this business type whose deciding "
            "fact is genuinely absent or contradicted (e.g. drone use for a "
            "photography studio; alcohol share for a restaurant). \n\n"
            "Do NOT overturn for: routine undocumented requirements, unstated "
            "dates/training/programs, ancillary coverages, generic ambiguity, or "
            "anything the completeness check already cleared. If you cannot name a "
            "specific decisive missing exclusion, UPHOLD ACCEPT.\n\n"
            f"Business type: {bt}\n"
            f"Prior reasoning: {state.get('reason','')}\n\n"
            f"=== APPLICATION ===\n{_app_text(app)[:9000]}\n\n"
            f"=== THIRD-PARTY DATA ===\n{_tpd_text(state['third_party_data'])}\n\n"
            f"=== GUIDELINES ===\n{guidelines[:4000]}\n\n"
            "Respond on a single line as JSON: "
            '{"decision": "<ACCEPT|REFER_TO_HUMAN_REVIEW>", '
            '"specific_missing_exclusion": "<name it, or empty if none>", '
            '"reason": "<one sentence>"}'
        )
        data = _parse_decision_json(self.llm.invoke(prompt).content)
        d = _normalize_decision(data.get("decision", tentative))
        named = (data.get("specific_missing_exclusion") or "").strip()
        # Discipline: only honor an escalation if the critic actually named a
        # specific decisive missing exclusion. A bare "REFER" with no concrete
        # gap is treated as over-caution and the ACCEPT is upheld.
        if d == "REFER_TO_HUMAN_REVIEW" and named:
            final = "REFER_TO_HUMAN_REVIEW"
        else:
            final = "ACCEPT"
        state["final_decision"] = final
        if data.get("reason"):
            verb = "escalated to REFER" if final != tentative else "confirmed ACCEPT"
            state["reason"] = f"[critic {verb}] {data['reason']}"
        return state

    # ---- graph ----
    def _build_graph(self):
        try:
            from langgraph.graph import StateGraph
        except Exception:
            return None

        from langgraph.graph import END

        flow = StateGraph(_AgenticState)
        flow.add_node("APPETITE_CHECK",      self._node_appetite_check)
        flow.add_node("REFLECTION",          self._node_reflection)
        flow.add_node("LOGISTIC_GATE",       self._node_logistic_gate)
        flow.add_node("COMPLETENESS_CHECK",  self._node_completeness_check)
        flow.add_node("THIRD_PARTY_EVAL",    self._node_third_party_eval)
        flow.add_node("ACCEPT",              self._node_accept)
        flow.add_node("FINAL_REJECT",        self._node_final_reject)
        flow.add_node("HUMAN_REVIEW",        self._node_human)
        flow.add_node("DECISION_REFLECTION", self._node_decision_reflection)

        flow.set_entry_point("APPETITE_CHECK")

        def appetite_router(state):
            a = state.get("appetite")
            if a == "OUT_OF_APPETITE": return "FINAL_REJECT"
            if a == "IN_APPETITE":     return "LOGISTIC_GATE"
            # UNCLEAR — optional Agent-3 reflection loop
            if (self.enable_appetite_reflection
                    and state.get("reflection_count", 0) < self.max_reflections):
                return "REFLECTION"
            return "HUMAN_REVIEW"
        flow.add_conditional_edges("APPETITE_CHECK", appetite_router)

        flow.add_edge("REFLECTION", "APPETITE_CHECK")

        # Logistic gate: hard quantitative fail -> REJECT; pass -> completeness.
        def logistic_router(state):
            if not state.get("logistic_pass", False):
                return "FINAL_REJECT"
            return "COMPLETENESS_CHECK"
        flow.add_conditional_edges("LOGISTIC_GATE", logistic_router)

        # Completeness: addresses exclusions -> ACCEPT; silent -> check TPD.
        def completeness_router(state):
            c = state.get("completeness")
            if c == "COMPLETE":  return "ACCEPT"
            return "THIRD_PARTY_EVAL"
        flow.add_conditional_edges("COMPLETENESS_CHECK", completeness_router)

        # TPD: reveals violation -> REJECT; affirmatively clean -> ACCEPT;
        # silent on the missing fact -> human review.
        def tpd_router(state):
            f = state.get("tpd_finding")
            if f == "REVEALS_VIOLATION":  return "FINAL_REJECT"
            if f == "CONFIRMS_CLEAN":     return "ACCEPT"
            return "HUMAN_REVIEW"
        flow.add_conditional_edges("THIRD_PARTY_EVAL", tpd_router)

        # Every tentative decision passes through the mandatory critic, which
        # produces the final decision and ends the graph.
        flow.add_edge("ACCEPT",        "DECISION_REFLECTION")
        flow.add_edge("FINAL_REJECT",  "DECISION_REFLECTION")
        flow.add_edge("HUMAN_REVIEW",  "DECISION_REFLECTION")
        flow.add_edge("DECISION_REFLECTION", END)

        return flow.compile()

    def run(self, application: dict, third_party: dict) -> dict:
        state: _AgenticState = {"application": application,
                                 "third_party_data": third_party,
                                 "reflection_count": 0}
        if self._graph is not None:
            out = self._graph.invoke(state)
        else:
            # Fallback linear flow (langgraph missing)
            out = self._node_appetite_check(state)
            reflections = 0
            while (out.get("appetite") == "UNCLEAR"
                   and self.enable_appetite_reflection
                   and reflections < self.max_reflections):
                out = self._node_reflection(out)
                out = self._node_appetite_check(out)
                reflections += 1
            if out.get("appetite") == "OUT_OF_APPETITE":
                out = self._node_final_reject(out)
            elif out.get("appetite") == "IN_APPETITE":
                out = self._node_logistic_gate(out)
                if not out.get("logistic_pass", False):
                    out = self._node_final_reject(out)
                else:
                    out = self._node_completeness_check(out)
                    if out.get("completeness") == "COMPLETE":
                        out = self._node_accept(out)
                    else:
                        out = self._node_third_party_eval(out)
                        f = out.get("tpd_finding")
                        if f == "REVEALS_VIOLATION":
                            out = self._node_final_reject(out)
                        elif f == "CONFIRMS_CLEAN":
                            out = self._node_accept(out)
                        else:
                            out = self._node_human(out)
            else:
                out = self._node_human(out)
            out = self._node_decision_reflection(out)
        final = out.get("final_decision") or "REFER_TO_HUMAN_REVIEW"
        return {
            "decision": _normalize_decision(final),
            "reason":   (out.get("reason") or "").strip()[:600],
            "appetite_decision": out.get("appetite"),
            "logistic_cap": _logistic_cap(application, third_party),
            "completeness": out.get("completeness"),
            "tpd_finding":  out.get("tpd_finding"),
            "reflections":  out.get("reflection_count", 0),
        }


# -----------------------------------------------------------------------------
# Convenience factory: instantiate the three pipelines with shared resources
# -----------------------------------------------------------------------------

@dataclass
class PipelineBundle:
    single: SingleLLMPipeline
    naive:  NaiveRAGPipeline
    agentic: AgenticRAGPipeline


def build_pipelines(*, llm, retriever, guidelines: GuidelineContext,
                    threshold: float = 1.75) -> PipelineBundle:
    return PipelineBundle(
        single  = SingleLLMPipeline(llm=llm, guidelines=guidelines, threshold=threshold),
        naive   = NaiveRAGPipeline(llm=llm, retriever=retriever, threshold=threshold),
        agentic = AgenticRAGPipeline(llm=llm, retriever=retriever, threshold=threshold),
    )
