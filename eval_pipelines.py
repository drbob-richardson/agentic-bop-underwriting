@dataclass
class GuidelineContext:
    global_text: str
    by_business: dict[str, str]

    @classmethod
    def from_files(cls, data_dir: str) -> "GuidelineContext":
        gpath = Path(data_dir) / "global_general_guidelines.json"
        spath = Path(data_dir) / "stage2_expanded_guidelines.json"
        gbpath = Path(data_dir) / "guidebook.json"

        global_text = ""
        if gpath.exists():
            with open(gpath) as f:
                gj = json.load(f)
            # Try several common shapes
            global_text = json.dumps(gj, indent=2)

        by_business: dict[str, str] = {}
        if spath.exists():
            with open(spath) as f:
                sj = json.load(f)
            for bt in sj.get("business_types", []):
                name = bt.get("business_type") or bt.get("name") or bt.get("business_type_id")
                if name:
                    by_business[name.strip().lower()] = json.dumps(
                        bt.get("expanded_guidelines", []), indent=2
                    )
        if gbpath.exists():
            with open(gbpath) as f:
                gb = json.load(f)
            for bt in gb.get("business_types", []):
                name = bt.get("name")
                if not name:
                    continue
                bucket = by_business.setdefault(name.strip().lower(), "")
                more = {
                    "restrictions": bt.get("restrictions", []),
                    "appetite":     bt.get("appetite", {}),
                    "notes":        bt.get("notes", ""),
                }
                by_business[name.strip().lower()] = (bucket + "\n" + json.dumps(more, indent=2)).strip()
        return cls(global_text=global_text, by_business=by_business)

    def for_business(self, business_type: str) -> str:
        bt = (business_type or "").strip().lower()
        return self.by_business.get(bt, "")


# -----------------------------------------------------------------------------
# Helper: robust JSON parse of LLM output
# -----------------------------------------------------------------------------

def _parse_decision_json(raw: str) -> dict:
    s = raw.strip()
    if s.startswith("```"):
        s = s.strip("`").replace("json\n", "").replace("json\r\n", "")
    try:
        return json.loads(s)
    except Exception:
        # Try to find the first {...} blob in the response
        m = re.search(r"\{.*\}", s, re.DOTALL)
        if m:
            try:
                return json.loads(m.group())
            except Exception:
                pass
    return {}


def _normalize_decision(s: str) -> str:
    s = (s or "").strip().upper()
    if "ACCEPT" in s and "REJECT" not in s and "REFER" not in s:
        return "ACCEPT"
    if "REJECT" in s and "REFER" not in s:
        return "REJECT"
    if "REFER" in s or "HUMAN" in s or "REVIEW" in s:
        return "REFER_TO_HUMAN_REVIEW"
    return "REFER_TO_HUMAN_REVIEW"  # default to refer on ambiguity


