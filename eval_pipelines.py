"""
eval_pipelines.py — the three underwriting pipelines from the paper, evaluated
on synthetic applications generated by bop_workbench.

Pipelines (all return {decision, reason} with decision ∈ {ACCEPT, REJECT, REFER_TO_HUMAN_REVIEW}):

  1. SingleLLMPipeline   — one LLM call with global+business guidelines inline.
  2. NaiveRAGPipeline    — retrieval over the guidebook PDF, then one LLM call.
  3. AgenticRAGPipeline  — multi-node LangGraph with reflection, third-party
                           checks, and a logistic risk score (per the paper).

Data-leakage safeguards
-----------------------
`sanitize_app_for_eval(raw_app_json)` strips every field that would tell a
pipeline the ground truth (ground_truth / chosen_reason / scenario / decision
/ _checks / meta). The pipelines only see the application form + third-party
data, the same surface that a real underwriter would.

Threshold convention
--------------------
The logistic risk score uses a single 1.75 cutoff (matching paper Appendix A
and the workbench generator). Below 1.75 = ACCEPT, at-or-above = REJECT.
The notebook's older 1.5/2.0 split is dropped in favor of the paper's single
threshold, so all three pipelines are on equal footing.
"""
