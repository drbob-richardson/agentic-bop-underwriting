_SINGLE_LLM_PROMPT = """\
You are an experienced commercial-insurance underwriter reviewing a Business
Owner Policy (BOP) application. Decide whether to ACCEPT, REJECT, or refer to
a human underwriter (REFER_TO_HUMAN_REVIEW).

Rules of the game:
- ACCEPT if the business's core operations are within appetite and nothing in
  the application evidences a violation of a specific guideline. A normal
  application never restates every requirement — do NOT withhold acceptance
  merely because routine documentation, dates, or ancillary details are
  unstated. Absence of a red flag is the common case for acceptance.
- REJECT if the application evidences a clear violation of a specific guideline
  (the prohibited activity is described or clearly implied).
- REFER_TO_HUMAN_REVIEW ONLY when a SPECIFIC, DECISIVE business-specific
  exclusion genuinely cannot be determined (the deciding fact is truly absent),
  not for incidental missing documentation or general ambiguity.

Respond with ONLY a single-line JSON object:
{{"decision": "<ACCEPT|REJECT|REFER_TO_HUMAN_REVIEW>", "reason": "<one short sentence citing the specific guideline or missing fact>"}}

==== APPLICATION ====
{app_text}

==== THIRD-PARTY DATA ====
{tpd_text}

==== GLOBAL GUIDELINES ====
{global_guidelines}

==== BUSINESS-SPECIFIC GUIDELINES ({business_type}) ====
{business_guidelines}
"""


def _app_text(application: dict) -> str:
    lines = []
    for k, v in application.items():
        if v in (None, ""):
            continue
        s = str(v)
        if len(s) > 800:
            s = s[:800] + "..."
        lines.append(f"{k}: {s}")
    blob = "\n".join(lines)
    if len(blob) > 14000:
        blob = blob[:14000] + "\n...[truncated]"
    return blob


def _tpd_text(third_party: dict) -> str:
    parts = []
    if third_party.get("Number of Claims") is not None:
        parts.append(f"Claims: {third_party['Number of Claims']} in last 3 years, "
                     f"total losses ${third_party.get('Total Losses', 0)}")
    if third_party.get("Google Rating") is not None:
        parts.append(f"Google rating: {third_party['Google Rating']}")
    revs = third_party.get("Google Reviews") or []
    if revs:
        parts.append("Google reviews:")
        for i, r in enumerate(revs, 1):
            if r:
                parts.append(f"  {i}. {r}")
    return "\n".join(parts)


class SingleLLMPipeline:
    """One LLM call with global + business guidelines, then logistic if accepted."""

    name = "single_llm"

    def __init__(self, llm, guidelines: GuidelineContext, threshold: float = 1.75):
        self.llm = llm
        self.guidelines = guidelines
        self.threshold = threshold

    def run(self, application: dict, third_party: dict) -> dict:
        business_type = application.get("NATURE OF BUSINESS") or "Unknown"
        prompt = _SINGLE_LLM_PROMPT.format(
            app_text=_app_text(application),
            tpd_text=_tpd_text(third_party),
            global_guidelines=(self.guidelines.global_text or "(none)")[:6000],
            business_guidelines=(self.guidelines.for_business(business_type) or "(no business-specific rules found)")[:4000],
            business_type=business_type,
        )
        raw = self.llm.invoke(prompt).content.strip()
        data = _parse_decision_json(raw)
        appetite_decision = _normalize_decision(data.get("decision", raw))
        reason = (data.get("reason") or "").strip() or raw[:200]

        if appetite_decision != "ACCEPT":
            return {"decision": appetite_decision, "reason": reason,
                    "appetite_decision": appetite_decision, "logistic_cap": None}

        # Appetite accepted → run logistic
        logit_dec, cap = logistic_decision(application, third_party, self.threshold)
        if logit_dec == "REJECT":
            return {"decision": "REJECT",
                    "reason": f"In appetite but failed statistical risk screen (cap={cap}).",
                    "appetite_decision": appetite_decision, "logistic_cap": cap}
        return {"decision": "ACCEPT", "reason": reason,
                "appetite_decision": appetite_decision, "logistic_cap": cap}


