# -----------------------------------------------------------------------------
# Sanitization — applied BEFORE any pipeline sees an app
# -----------------------------------------------------------------------------

# Keys we strip at the top of the raw JSON file.
_LEAKAGE_TOP_KEYS = {
    "ground_truth", "chosen_reason", "scenario", "validation",
    "mode", "business_type",
}
# Keys we strip from app["app"] (the inner application dict).
_LEAKAGE_APP_KEYS = {
    "ground_truth", "chosen_reason", "scenario", "decision",
    "_checks", "meta", "business_type",
}
# Keys we strip from app["app"]["THIRD PARTY"]["GOOGLE_REVIEWS"] (introduced
# by the TPD-injector — they label that we seeded a violation).
_LEAKAGE_TPD_REVIEW_KEYS = {
    "tpd_violation_seeded", "tpd_violation_reason",
}


def sanitize_app_for_eval(raw: dict) -> dict:
    """Return a deep-copied raw record with all ground-truth signals removed.

    Input shape (from bop_workbench output):
        {
          "app": { "FIELDS": {...}, "THIRD PARTY": {...},
                   "scenario": ..., "decision": ..., "_checks": ..., "meta": ...,
                   "ground_truth": {...}, "chosen_reason": {...},
                   "business_type": ... },
          "scenario": ..., "business_type": ..., "chosen_reason": ...,
          "ground_truth": ..., "validation": ..., "mode": ...
        }

    Output: only the application form + third-party data plus what the
    paper says an underwriter sees. NATURE OF BUSINESS / SIC remain because
    they're explicit application fields.
    """
    raw = copy.deepcopy(raw)
    inner = raw.get("app", raw)
    # Strip top-level
    for k in list(raw.keys()):
        if k in _LEAKAGE_TOP_KEYS:
            raw.pop(k, None)
    # Strip inner application keys
    if isinstance(inner, dict):
        for k in list(inner.keys()):
            if k in _LEAKAGE_APP_KEYS:
                inner.pop(k, None)
        # Strip TPD review labels
        tp = inner.get("THIRD PARTY", {})
        if isinstance(tp, dict):
            grev = tp.get("GOOGLE_REVIEWS", {})
            if isinstance(grev, dict):
                for k in list(grev.keys()):
                    if k in _LEAKAGE_TPD_REVIEW_KEYS:
                        grev.pop(k, None)
    return raw


def flat_application_view(sanitized: dict) -> tuple[dict, dict]:
    """Convert a sanitized record into (flat_application, flat_third_party).

    The pipelines internally use a flat dict keyed by field name, matching the
    shape the original notebook expected. This keeps the pipelines independent
    of the workbench's nested layout.
    """
    inner = sanitized.get("app", sanitized)
    fields = (inner.get("FIELDS") or {}).copy()
    tp = inner.get("THIRD PARTY") or {}

    # Aliases the agentic pipeline reads
    aliases = {
        "Year Built":          ("Year Built", "YEAR BUILT"),
        "Square Feet":         ("Square Feet", "SQUARE FOOTAGE"),
        "Building limit":      ("Building limit", "BUILDING LIMIT"),
        "ANNUAL SALES":        ("ANNUAL SALES", "Annual Sales"),
        "Distance to hydrant": ("Distance to hydrant", "DISTANCE TO HYDRANT"),
        "NATURE OF BUSINESS":  ("NATURE OF BUSINESS",),
        "SIC":                 ("SIC",),
    }
    flat_app: dict = dict(fields)
    for canonical, opts in aliases.items():
        for k in opts:
            if k in fields and fields[k] not in (None, ""):
                flat_app[canonical] = fields[k]
                break
    flat_tp = {
        "Number of Claims": (tp.get("CLAIMS_HISTORY") or {}).get("num_claims", 0),
        "Total Losses":     (tp.get("CLAIMS_HISTORY") or {}).get("total_losses", 0),
        "Google Rating":    tp.get("GOOGLE_RATING"),
        "Google Reviews":   (tp.get("GOOGLE_REVIEWS") or {}).get("reviews", []),
    }
    return flat_app, flat_tp


# -----------------------------------------------------------------------------
# Logistic risk score (single 1.75 cutoff)
# -----------------------------------------------------------------------------

import datetime as _dt

_SIC_BASE_RATES = {
    "20": 0.40, "50": 0.40, "52": 0.35, "53": 0.35, "54": 0.35,
    "55": 0.35, "56": 0.35, "57": 0.35, "58": 0.70, "59": 0.35,
    "72": 0.55, "73": 0.55, "75": 0.55, "76": 0.55, "80": 0.50,
    "81": 0.50, "82": 0.50, "87": 0.50, "40": 0.45, "41": 0.45,
    "42": 0.45, "48": 0.45,
}


def _num(v, default=None):
    s = "" if v is None else str(v)
    m = re.search(r"-?\d[\d,]*\.?\d*", s)
    if not m:
        return default
    try:
        return float(m.group().replace(",", ""))
    except Exception:
        return default


def _logistic_cap(application: dict, third_party: dict) -> float:
    sic = str(application.get("SIC", "")) or "9999"
    sic = re.sub(r"\D", "", sic) or "9999"
    sic = (sic + "0000")[:4]
    base = _SIC_BASE_RATES.get(sic[:2], 0.50)

    year_built = int(_num(application.get("Year Built"), 2000) or 2000)
    year_built = max(year_built, 1850)
    sq_ft = max(_num(application.get("Square Feet"), 3000.0) or 3000.0, 100.0)
    bld   = max(_num(application.get("Building limit"), 500_000.0) or 500_000.0, 0.0)
    hyd   = max(_num(application.get("Distance to hydrant"), 500.0) or 500.0, 0.0)
    sales = max(_num(application.get("ANNUAL SALES"), 300_000.0) or 300_000.0, 1_000.0)
    claims = max(int(_num(third_party.get("Number of Claims"), 0) or 0), 0)

    age = min(_dt.datetime.now().year - year_built, 80)
    age_factor    = 0.75 + 0.0075 * age
    sq_ft_factor  = (sq_ft / 2000) ** 0.15
    limit_factor  = min(1 + 0.002 * max(0, bld / 1000 - 250), 3.0)
    hydrant_factor= min(1 + 0.00003 * hyd, 1.30)
    loss_factor   = min(1.0 * (1.25 ** claims), 3.0)
    sales_factor  = (sales / 100_000) ** 0.10
    total = age_factor * sq_ft_factor * limit_factor * hydrant_factor * loss_factor * sales_factor * base
    return float(round(max(min(total, 2.5), 0.5), 3))


def logistic_decision(application: dict, third_party: dict,
                       threshold: float = 1.75) -> tuple[str, float]:
    cap = _logistic_cap(application, third_party)
    return ("ACCEPT" if cap < threshold else "REJECT"), cap


